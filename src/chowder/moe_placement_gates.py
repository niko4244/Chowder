"""The gate table a MoE placement's pre-registration owns, and the rule that keeps it honest.

A placement's prereg is only worth the numbers in it. Those numbers live in one
generated block inside the prereg document -- `chowder_batch/moe_int8_gates.py`
measures them and replaces that block, so the table cannot drift from the last
measurement -- and this module is the single definition of that block: how it is
rendered, how it is read back, what counts as a regression, and when a campaign
is allowed to declare the placement at all.

Why the numbers are not trusted once recorded:

- a gate recorded as measured cannot silently become unmeasured, a pass cannot
  become a fail, and a timed or sized number cannot grow past
  ``REGRESSION_TOLERANCE`` -- ``regressions`` says so, and the runner exits
  non-zero on it;
- the block records the artifact it was measured on, so a table measured against
  one checkpoint can never be presented as evidence for another. The digest is
  the config's own sha256 plus the shard inventory
  (``artifact_identity``), which the runner and the declaration guard both
  compute the same way;
- a campaign declaring the placement is refused while any gate is unmeasured,
  failed, or was measured on a different artifact (``assert_declaration_allowed``).

A row the new measurement cannot answer (e.g. ``--steps 0`` answers no
throughput) is carried forward from the previous measurement rather than
overwritten with "not measured": the last real number stays visible, and the
block names the rows that were carried.
"""

from __future__ import annotations

import hashlib
import os
import re
from pathlib import Path
from typing import Any

#: The worker placement these gates qualify.
EXPERT_PLACEMENT = "cpu-transient-grad-int8"

#: The card the placement exists for: peak allocated VRAM per step, in GB.
VRAM_GATE_GB = 14.5

BLOCK_BEGIN = (
    "<!-- BEGIN moe-int8-gates (generated by chowder_batch/moe_int8_gates.py; "
    "do not edit by hand) -->"
)
BLOCK_END = "<!-- END moe-int8-gates -->"
DEFAULT_PREREG = "docs/quals/MOE_INT8_PLACEMENT_PREREG_2026-10-20.md"

#: A numeric gate that moves the wrong way by more than this share is a regression.
REGRESSION_TOLERANCE = 0.10

#: Gates ``chowder_batch/moe_int8_gates.py`` measures.
RUNNER_GATES = ("load_census", "memory_vram", "host_rss", "throughput")
#: Gates that need a worker run (a dataset, a real fine-tune) before this
#: placement may be declared; the runner records them as not measured and
#: ``placement_witnesses`` produces them.
WITNESS_GATES = ("gradient", "smoke", "router_balance", "wddm_spill")
ALL_GATES = RUNNER_GATES + WITNESS_GATES
#: The one gate no tool can observe: an operator records it with a basis.
OPERATOR_GATES = ("wddm_spill",)
#: What a witness file declares itself to be.
WITNESS_SCHEMA = "chowder.moe-placement-witnesses.v1"
WITNESS_VERDICTS = ("pass", "FAIL", "not measured")

#: Gates whose direction is "smaller is better" and whose number is compared
#: against the recorded one.
SIZE_GATES = ("memory_vram", "throughput", "load_census", "host_rss")


class PlacementGateError(ValueError):
    """A declaration backed by a table that cannot support it."""


def code_commit() -> str | None:
    """The commit the numbers were produced by, when this is a git checkout."""
    import subprocess

    try:
        completed = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, timeout=10
        )
        return completed.stdout.strip() or None if completed.returncode == 0 else None
    except Exception:
        return None


def repo_root() -> Path | None:
    """The checkout this module is installed from, if it is a checkout at all."""
    here = Path(__file__).resolve()
    for parent in here.parents:
        if (parent / DEFAULT_PREREG).is_file() or (parent / "docs" / "quals").is_dir():
            return parent
    return None


def resolve_prereg_path(explicit: str | Path | None = None) -> Path | None:
    """Where the placement's prereg lives, or ``None`` when this tree has none."""
    override = explicit or os.environ.get("CHOWDER_MOE_GATE_TABLE") or ""
    if override:
        return Path(override)
    root = repo_root()
    return None if root is None else root / DEFAULT_PREREG


def artifact_identity(base: str | Path) -> dict[str, Any]:
    """What the numbers belong to: a config digest and the shard inventory.

    A path or a tag is not identity -- the same directory can hold a different
    prune -- so the record carries the digest the numbers were measured against.
    """
    base = Path(base)
    config = base / "config.json"
    digest = hashlib.sha256(config.read_bytes()).hexdigest() if config.is_file() else None
    shards = sorted(base.glob("*.safetensors"))
    return {
        "config_sha256": digest,
        "shards": len(shards),
        "shard_bytes": sum(path.stat().st_size for path in shards),
    }


def gate_rows(record: dict[str, Any], *, placement: str = EXPERT_PLACEMENT) -> list[tuple[str, str, str]]:
    """``(gate, value, verdict)`` for the placement arm of a gate record."""
    arm = (record.get("arms") or {}).get("int8") or {}
    gates = arm.get("gates") or {}
    census = arm.get("census") or {}
    census_meta = arm.get("census_meta") or {}
    rows: list[tuple[str, str, str]] = [
        (
            "load_census",
            f"{census_meta.get('expert_bytes_gb')} GB int8+scales, "
            f"{census.get('patched_expert_modules')} modules patched, "
            f"{census.get('remaining_expert_params')} live bf16 expert params",
            "measured" if gates.get("load_census") == "measured" else "not measured",
        )
    ]
    peak = arm.get("peak_vram_gb")
    rows.append(
        (
            "memory_vram",
            "not measured (CPU arm)" if peak is None else f"{peak} GB peak (gate <= {VRAM_GATE_GB} GB)",
            (
                "not measured"
                if peak is None or gates.get("memory_vram_pass") is None
                else ("pass" if gates["memory_vram_pass"] else "FAIL")
            ),
        )
    )
    rows.append(
        (
            "host_rss",
            f"{arm.get('total_peak_rss_gb')} GB peak "
            f"({arm.get('load_peak_rss_gb')} GB at load)",
            "measured" if gates.get("host_rss") == "measured" else "not measured",
        )
    )
    s_per_step = arm.get("s_per_step")
    rows.append(
        (
            "throughput",
            (
                "not measured (--steps 0)"
                if s_per_step is None
                else f"{s_per_step} s/placement-step (spread {_step_noise(arm)} s)"
            ),
            "measured (placement step)" if s_per_step is not None else "not measured",
        )
    )
    # The gates this runner cannot measure are rendered from whatever the record
    # says about them, so a worker run that *can* answer them lands in the same
    # table -- and its "not measured" stand-ins read as unmeasured here, which is
    # what keeps the declaration rule honest.
    for gate in WITNESS_GATES:
        status = str(gates.get(gate, "not measured"))
        rows.append((gate, status, _verdict(status)))
    return rows


def _step_noise(arm: dict[str, Any]) -> float:
    """Spread of the timed steps: a comparison inside this band is not a change."""
    times = [float(value) for value in (arm.get("step_seconds") or ()) if value is not None]
    return round(max(times) - min(times), 4) if len(times) >= 2 else 0.0


def _verdict(status: str) -> str:
    """How a record's gate status reads in the table."""
    text = status.strip()
    if not text or text.lower().startswith(("not measured", "not observable")):
        return "not measured"
    if text.startswith("FAIL"):
        return "FAIL"
    return text


def merge_rows(
    new_rows: list[tuple[str, str, str]], previous: dict[str, Any] | None
) -> tuple[list[tuple[str, str, str]], list[str]]:
    """Keep the last real number for a gate this run could not answer.

    Overwriting a measured row with "not measured" would erase the only evidence
    the placement ever had; the row is carried forward instead, and named.
    """
    if previous is None:
        return list(new_rows), []
    prior = {gate: (previous["values"][gate], verdict) for gate, verdict in previous["verdicts"].items()}
    merged: list[tuple[str, str, str]] = []
    carried: list[str] = []
    for gate, value, verdict in new_rows:
        old = prior.get(gate)
        if old is not None and verdict.startswith("not measured") and not old[1].startswith("not measured"):
            merged.append((gate, old[0], old[1]))
            carried.append(gate)
        else:
            merged.append((gate, value, verdict))
    return merged, carried


def render_block(record: dict[str, Any], *, previous: dict[str, Any] | None = None) -> str:
    """The prereg's generated block: the table, its provenance, nothing else."""
    artifact = record.get("artifact") or {}
    arm = (record.get("arms") or {}).get("int8") or {}
    bulk = (record.get("arms") or {}).get("bulk") or {}
    rows, carried = merge_rows(gate_rows(record), previous)
    lines = [BLOCK_BEGIN, "", "| gate | value | verdict |", "|---|---|---|"]
    for gate, value, verdict in rows:
        lines.append(f"| `{gate}` | {value} | {verdict} |")
    lines += [
        "",
        f"- artifact: `{record.get('base_model')}` config sha256 "
        f"`{artifact.get('config_sha256')}`, {artifact.get('shards')} shards, "
        f"{artifact.get('shard_bytes')} bytes",
        f"- measured at {record.get('measured_at')} on {record.get('device')} "
        f"({record.get('steps')} steps, seq {record.get('seq_len')}), "
        f"code `{record.get('code_commit')}`",
        f"- int8 placement step: {_seconds(arm.get('s_per_step'))}; "
        f"bulk comparison arm: {_seconds(bulk.get('s_per_step'))}",
    ]
    # A witness gate recorded by a worker run keeps its provenance line: the
    # runner can carry the row forward but it did not produce it.
    for line in (previous or {}).get("provenance", ()):
        lines.append(line)
    if carried:
        lines.append(f"- carried forward from the previous measurement: `{'`, `'.join(carried)}`")
    lines += ["", BLOCK_END]
    return "\n".join(lines)


def _seconds(value: Any) -> str:
    """A timed value, or that it was not measured -- never ``None s``."""
    return "not measured" if value is None else f"{value} s"


def parse_block(document: str) -> dict[str, Any] | None:
    """Read a rendered block back: gate verdicts, values, numbers, provenance."""
    start = document.find(BLOCK_BEGIN)
    end = document.find(BLOCK_END)
    if start < 0 or end < 0 or end < start:
        return None
    block = document[start : end + len(BLOCK_END)]
    verdicts: dict[str, str] = {}
    values: dict[str, str] = {}
    for line in block.splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) == 3 and cells[0].startswith("`"):
            values[cells[0].strip("`")] = cells[1]
            verdicts[cells[0].strip("`")] = cells[2]
    numbers: dict[str, float] = {}
    for gate, value in values.items():
        try:
            numbers[gate] = float(value.split(" ")[0])
        except ValueError:
            continue
    sha = None
    for line in block.splitlines():
        if "config sha256" in line:
            match = re.search(r"sha256\s*`([^`]*)`", line)
            sha = (match.group(1) or None) if match else None
            break
    carried = [
        gate.strip().strip("`")
        for line in block.splitlines()
        if line.startswith("- carried forward from the previous measurement:")
        for gate in line.split(":", 1)[1].split(",")
    ]
    provenance = [
        line for line in block.splitlines() if line.startswith("- witness gates:")
    ]
    return {
        "verdicts": verdicts,
        "values": values,
        "numbers": numbers,
        "config_sha256": sha,
        "carried": carried,
        "provenance": provenance,
        "block": block,
    }


def splice_block(document: str, block: str) -> str:
    """Replace the generated block in place, or append it: prose is never touched."""
    start = document.find(BLOCK_BEGIN)
    end = document.find(BLOCK_END)
    if start < 0 or end < 0 or end < start:
        return document.rstrip() + "\n\n" + block + "\n"
    return document[:start] + block + document[end + len(BLOCK_END) :]


def splice_witness_rows(document: str, witness: dict[str, Any]) -> tuple[str, list[str]]:
    """Record a worker run's witness gates in the table, touching only those rows.

    The runner owns the rows it measures; a worker run owns the four it does
    not. So this replaces exactly the witness rows inside the existing block and
    leaves every other row -- and the prose around the block -- as it was.
    Refusals, all raised before anything is written:

    * the table has no block yet (run the runner first: it is what binds the
      table to an artifact);
    * the witness was measured on another artifact than the table;
    * a gate would be downgraded from measured/pass to not measured -- a run
      that did not observe a gate cannot clear the verdict another run earned;
    * an operator gate recorded as a verdict with no basis (``evidence.basis``),
      which would be a hand-edit wearing a measurement's clothes.
    """
    parsed = parse_block(document)
    if parsed is None:
        raise PlacementGateError(
            "the prereg has no gate table to record witnesses into; run "
            "chowder_batch/moe_int8_gates.py against the artifact first (its table "
            "is what binds the numbers to a checkpoint)"
        )
    if str(witness.get("schema", "")) != WITNESS_SCHEMA:
        raise PlacementGateError(
            f"witness schema {witness.get('schema')!r} is not {WITNESS_SCHEMA!r}"
        )
    if str(witness.get("placement", "")) != EXPERT_PLACEMENT:
        raise PlacementGateError(
            f"witness placement {witness.get('placement')!r} is not {EXPERT_PLACEMENT!r}"
        )
    gates = witness.get("gates") or {}
    if not isinstance(gates, dict) or not gates:
        raise PlacementGateError("the witness file records no gates")
    unknown = sorted(set(gates) - set(WITNESS_GATES))
    if unknown:
        raise PlacementGateError(
            f"the witness file records {unknown}, which this runner does not own; a "
            f"witness may only write {list(WITNESS_GATES)}"
        )
    recorded_on = parsed.get("config_sha256")
    witness_on = (witness.get("artifact") or {}).get("config_sha256")
    if not recorded_on:
        raise PlacementGateError(
            "the table names no artifact yet, so a witness cannot be bound to it; "
            "run chowder_batch/moe_int8_gates.py against the base model first"
        )
    if witness_on != recorded_on:
        raise PlacementGateError(
            f"the witness was measured on config sha256 `{witness_on}` but the table "
            f"was measured on `{recorded_on}`; these numbers are not about the same artifact"
        )

    # Every gate, in the table's own order, so recording a witness on an older
    # table completes it instead of quietly narrowing it.
    rows: list[tuple[str, str, str]] = [
        (gate, parsed["values"].get(gate, "not measured"), parsed["verdicts"].get(gate, "not measured"))
        for gate in ALL_GATES
        if gate in parsed["verdicts"] or gate in gates
    ]
    replaced: dict[str, tuple[str, str, str]] = {}
    for gate, entry in gates.items():
        if not isinstance(entry, dict):
            raise PlacementGateError(f"{gate}: a witness entry must be an object, got {type(entry).__name__}")
        verdict = str(entry.get("verdict", "not measured"))
        if verdict not in WITNESS_VERDICTS:
            raise PlacementGateError(
                f"{gate}: witness verdict {verdict!r} is not one of {list(WITNESS_VERDICTS)}"
            )
        previous = parsed["verdicts"].get(gate, "not measured")
        if verdict.startswith("not measured") and not previous.startswith("not measured"):
            raise PlacementGateError(
                f"{gate}: the table records {previous!r} and this run did not measure it; "
                "a run that observed nothing cannot clear a verdict another run earned"
            )
        if gate in OPERATOR_GATES and not verdict.startswith("not measured"):
            basis = str((entry.get("evidence") or {}).get("basis", "")).strip()
            if not basis:
                raise PlacementGateError(
                    f"{gate} is an operator gate: record it with evidence.basis naming what "
                    "the verdict rests on (PyTorch cannot observe driver paging)"
                )
        replaced[gate] = (gate, str(entry.get("value", verdict)), verdict)
    if not replaced:
        return document, []

    merged = [replaced.get(gate, (gate, value, verdict)) for gate, value, verdict in rows]
    lines = [
        line
        for line in parsed["block"].splitlines()
        if line.startswith("- ")
        and not line.startswith("- witness gates:")
        and not line.startswith("- carried forward from the previous measurement:")
    ]
    lines.append(
        f"- witness gates: `{'`, `'.join(sorted(replaced))}` recorded {witness.get('measured_at')} "
        f"by {witness.get('run') or 'a worker run'} on {witness.get('device')} "
        f"({witness.get('steps')} steps), code `{witness.get('code_commit')}`"
    )
    carried = [
        line
        for line in parsed["block"].splitlines()
        if line.startswith("- carried forward from the previous measurement:")
    ]
    block = _compose_block(merged, lines + carried)
    return splice_block(document, block), sorted(replaced)


def _compose_block(rows: list[tuple[str, str, str]], extra_lines: list[str]) -> str:
    lines = [BLOCK_BEGIN, "", "| gate | value | verdict |", "|---|---|---|"]
    lines += [f"| `{gate}` | {value} | {verdict} |" for gate, value, verdict in rows]
    lines += ["", *extra_lines, "", BLOCK_END]
    return "\n".join(lines)


def numeric_gates(record: dict[str, Any]) -> dict[str, float | None]:
    """The comparable number behind each sized or timed gate."""
    arm = (record.get("arms") or {}).get("int8") or {}
    return {
        "memory_vram": arm.get("peak_vram_gb"),
        "throughput": arm.get("s_per_step"),
        "load_census": (arm.get("census_meta") or {}).get("expert_bytes_gb"),
        "host_rss": arm.get("total_peak_rss_gb"),
    }


def regressions(previous: dict[str, Any] | None, record: dict[str, Any]) -> list[str]:
    """Every way the new measurement is worse than the recorded one.

    A gate the table records as measured cannot silently become unmeasured, a
    pass cannot become a fail, a sized or timed number cannot grow by more than
    ``REGRESSION_TOLERANCE``, and numbers measured on another artifact are not
    comparable at all.
    """
    if previous is None:
        return []
    problems: list[str] = []
    # Judged on the rows the table would carry: a gate this run could not answer
    # keeps its recorded value, so it has not regressed -- it has gone unmeasured
    # only in this run, and the earlier number is still what the table shows.
    current = {gate: verdict for gate, _value, verdict in merge_rows(gate_rows(record), previous)[0]}
    for gate, verdict in previous["verdicts"].items():
        if verdict.startswith("not measured") or gate not in current:
            continue
        now = current[gate]
        if verdict == "pass" and now != "pass":
            problems.append(f"{gate}: was pass, now {now}")
        elif not now.startswith("not measured") and verdict != now and gate not in SIZE_GATES:
            problems.append(f"{gate}: was {verdict!r}, now {now!r}")
        elif now.startswith("not measured"):
            problems.append(f"{gate}: recorded as measured, now unmeasured")
    old, new = previous["numbers"], numeric_gates(record)
    # A timed step is compared only outside its own spread: on a tiny model a
    # 10% band is smaller than the run-to-run jitter of the timer itself, and a
    # gate that cries wolf on noise is a gate an operator learns to ignore.
    noise = _step_noise((record.get("arms") or {}).get("int8") or {})
    for gate in SIZE_GATES:
        if gate not in old or new.get(gate) is None or old[gate] <= 0:
            continue
        allowed = old[gate] * (1 + REGRESSION_TOLERANCE) + (noise if gate == "throughput" else 0.0)
        if new[gate] > allowed:
            problems.append(
                f"{gate}: {new[gate]} is worse than the recorded {old[gate]} "
                f"(allowed up to {round(allowed, 3)})"
            )
    if previous.get("config_sha256") and (record.get("artifact") or {}).get("config_sha256"):
        if previous["config_sha256"] != record["artifact"]["config_sha256"]:
            problems.append(
                "artifact: the config digest differs from the recorded one, so these numbers "
                "are not comparable to the table"
            )
    return problems


def assert_declaration_allowed(
    prereg_text: str,
    declarations: list[str],
    *,
    base_model: str | Path | None = None,
) -> dict[str, Any]:
    """Refuse a campaign that declares this placement on a table that cannot back it.

    ``declarations`` are the places (paths or names) that declare
    ``expert_placement``; each is only allowed once every gate in the table is
    measured with none in FAIL, and -- when the base model is known -- once the
    table was measured on that same artifact.
    """
    if not declarations:
        return {}
    parsed = parse_block(prereg_text)
    if parsed is None:
        raise PlacementGateError(
            f"{declarations[0]} declares expert_placement={EXPERT_PLACEMENT!r} but the prereg "
            "has no gate table; run chowder_batch/moe_int8_gates.py against the artifact first"
        )
    unmeasured = [gate for gate, verdict in parsed["verdicts"].items() if verdict.startswith("not measured")]
    failed = [gate for gate, verdict in parsed["verdicts"].items() if verdict == "FAIL"]
    missing = [gate for gate in ALL_GATES if gate not in parsed["verdicts"]]
    if unmeasured or failed or missing:
        raise PlacementGateError(
            f"{declarations[0]} declares expert_placement={EXPERT_PLACEMENT!r} but the prereg "
            f"table is not satisfied: unmeasured={sorted(unmeasured)}, failed={sorted(failed)}, "
            f"missing={sorted(missing)}"
        )
    if base_model is not None:
        measured_on = parsed.get("config_sha256")
        declared_on = artifact_identity(base_model)["config_sha256"]
        if measured_on != declared_on:
            raise PlacementGateError(
                f"{declarations[0]} declares expert_placement={EXPERT_PLACEMENT!r} but the gate "
                f"table was measured on a different artifact (config sha256 `{measured_on}`) than "
                f"the declared base ({declared_on!r}); re-run "
                "chowder_batch/moe_int8_gates.py against this base"
            )
    return parsed
