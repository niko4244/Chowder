def test_s0_a_fake_training_fn_drives_the_cycle_to_a_recorded_promotion(tmp_path: Path):
    """S0: the joined cycle runs Model N -> decision -> ledger with no gaps.

    The merged framework shipped this seam with no coverage at all, so the
    binding's positive control is that the seam it plugs into actually works:
    curriculum -> recipes -> training evidence -> predeclared promotion ->
    lineage record.
    """
    calls: list[str] = []

    def fake_train(recipe, items):  # noqa: ANN001
        calls.append(recipe.recipe_id)
        evidence = tmp_path / f"{recipe.recipe_id}-evidence.json"
        evidence.write_text(json.dumps({"recipe_id": recipe.recipe_id}), encoding="utf-8")
        return {
            "status": "SUCCEEDED",
            "measured_gpu_hours": 0.02,
            "evidence_path": str(evidence),
            "worst_expert_fraction": 0.0,
        }

    cycle = _cycle(tmp_path, fake_train)
    profile = CapabilityProfile(
        model_version="gen0",
        raw_scores={TARGET_ID: 0.25},
        skills=tuple(
            SkillEstimate(skill=s, estimate=0.25, confidence=0.9, evidence=(TARGET_ID,))
            for s in ALL_SKILLS
        ),
    )
    items = cycle.plan_curriculum(profile)
    assert items, "the curriculum phase must produce items for a measured profile"

    recipes = (_recipe(item_ids=[i.item_id for i in items]),)
    results = cycle.train_candidates(items, recipes)
    assert calls == ["recipe-00"]
    assert results[0]["recipe_id"] == "recipe-00"

    def _samples(mean: float) -> tuple[float, ...]:
        # Real spread: the promotion rule is a statistical test, and a constant
        # sample cannot be called significant without inventing variance.
        return (mean - 0.03,) * 3 + (mean + 0.03,) * 3

    def _measured(score: float, other: float, *, origin: str) -> dict[str, BenchmarkResult]:
        return {
            TARGET_ID: BenchmarkResult(
                benchmark_qualified_id=TARGET_ID,
                score=score,
                samples=_samples(score),
                contamination="CLEAN",
                measurement_origin=origin,
            ),
            PROTECTED_ID: BenchmarkResult(
                benchmark_qualified_id=PROTECTED_ID,
                score=other,
                samples=_samples(other),
                contamination="CLEAN",
                measurement_origin=origin,
            ),
            BROAD_ID: BenchmarkResult(
                benchmark_qualified_id=BROAD_ID,
                score=other,
                samples=_samples(other),
                contamination="CLEAN",
                measurement_origin=origin,
            ),
        }

    decision = cycle.decide_promotion(
        candidate_results=_measured(0.62, 0.80, origin=MEASURED_THIS_GENERATION),
        parent_results=_measured(0.30, 0.80, origin=MEASURED_PARENT),
        device_gpu_hours=results[0]["measured_gpu_hours"],
    )
    assert decision.verdict == "PROMOTED", decision.reasons

    outcome = cycle.finalize(
        decision,
        base_model={"path": "F:/llm-models/tiny", "manifest_sha256": "0" * 64},
        dataset_manifest_ref=str(tmp_path / "dataset.json"),
        curriculum_manifest_ref=str(tmp_path / "curriculum.json"),
        recipe=recipes[0].to_dict(),
        training_evidence_ref=results[0]["evidence_path"],
        evaluation_report_ref=str(tmp_path / "eval-report.json"),
    )
    assert outcome.verdict == "PROMOTED"
    assert [p.phase for p in outcome.phases] == ["promotion"]
    assert cycle.ledger.get("gen1").parent_version == "gen0"
    assert cycle.ledger.get("gen1").training_evidence_ref == results[0]["evidence_path"]


