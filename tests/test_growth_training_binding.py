"""The growth cycle's `TrainingFn`, bound to the production trainer.

PR #166 merged the growth system with its trainer seam exercised only against
tiny local fakes. A fake trainer cannot demonstrate project validation, budget
enforcement, registry lifecycle, contamination binding, worker source identity,
or independent evaluation. This module tests the *binding* -- the thing that
turns the merged framework into authority to train.

The nine acceptance properties are the contract
(``docs/GROWTH_TRAINFN_BINDING_PLAN_2026-09-16.md``); the layers below mirror
its proof ladder:

* the **contract** layer (S0) proves the cycle seam itself, which had no
  coverage at all: a fake ``TrainingFn`` drives Model N -> promotion end to end;
* the **refusal** layer proves properties 2, 4, 5 and 9 hold *before* compute.
  Each refusal is asserted to have started no training subprocess -- a refusal
  that already ran the trainer is not a refusal;
* the **real** layer (S1-S6) drives a genuine tiny Qwen3 MoE through actual
  ``chowder project-validate`` and ``chowder train`` processes and requires the
  resulting rows to be terminal in the production registry.

The real layer needs torch/transformers, so it is gated the way the router
project suite is: it runs in the real-ML job, where a silent skip shows up in
the skip count.
"""

