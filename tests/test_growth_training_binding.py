def _recipe(*, recipe_id: str = "recipe-00", max_steps: int = 4, seq_len: int = 16,
            learning_rate: float = 0.05, item_ids: Sequence[str] = ()) -> TrainingRecipe:
    """A bounded recipe built directly, not through the planner.

    The planner always proposes ``seq_len`` 2048 for a real model; the ladder
    needs a 16-token tiny model. The planner's probe/kill conditions are covered
    by their own tests, and the binding's contract is "given a recipe, execute
    it" -- so the ladder supplies the recipe and lets the binding do the rest.
    """
    return TrainingRecipe(
        recipe_id=recipe_id,
        curriculum_item_ids=tuple(item_ids),
        mixture={"TARGET": 0.6, "PRESERVE": 0.2, "REPLAY": 0.2},
        learning_rate=learning_rate,
        scheduler="constant",
        warmup_steps=0,
        lora_rank=8,
        lora_alpha=16,
        target_modules=("q_proj", "v_proj"),
        seq_len=seq_len,
        batch_size=2,
        gradient_accumulation=1,
        max_steps=max_steps,
        objective="sft",
        replay_rate=0.2,
        dataset_manifest={"items": list(item_ids)},
        projected_device_gpu_hours=0.01,
        projected_wall_gpu_hours=0.035,
    )


