def _build_tiny_base(root: Path) -> dict[str, Path]:
    import torch
    from tokenizers import Tokenizer, models, pre_tokenizers, trainers
    from transformers import PreTrainedTokenizerFast
    from transformers.models.qwen3_moe import Qwen3MoeConfig, Qwen3MoeForCausalLM

    lines = [
        f"the router selects expert {index % 4} for token number {index} in this sentence"
        for index in range(400)
    ]
    holdout = root / "holdout.txt"
    holdout.write_text(
        "\n".join(
            f"held out sentence {index} asks which expert answers token {index * 3}"
            for index in range(400)
        ),
        encoding="utf-8",
    )

    tokenizer = Tokenizer(models.WordLevel(unk_token="[UNK]"))
    tokenizer.pre_tokenizer = pre_tokenizers.Whitespace()
    tokenizer.train_from_iterator(
        lines, trainers.WordLevelTrainer(vocab_size=64, special_tokens=["[UNK]", "[PAD]"])
    )
    fast = PreTrainedTokenizerFast(
        tokenizer_object=tokenizer, unk_token="[UNK]", pad_token="[UNK]"
    )

    torch.manual_seed(0)
    config = Qwen3MoeConfig(
        vocab_size=64,
        hidden_size=16,
        intermediate_size=8,
        moe_intermediate_size=8,
        num_hidden_layers=2,
        num_attention_heads=2,
        num_key_value_heads=1,
        num_experts=4,
        num_experts_per_tok=2,
        max_position_embeddings=64,
    )
    base = root / "base"
    Qwen3MoeForCausalLM(config).float().save_pretrained(base)
    fast.save_pretrained(base)
    return {"base": base, "holdout": holdout}


def _real_binding(tmp_path: Path, tiny_base, *, template=None, **overrides: Any) -> SubprocessTrainingFn:
    template = template if template is not None else _template(tmp_path)
    knobs = template["config"]["backend"]["router_healing"]
    knobs["base_model_dir"] = str(tiny_base["base"])
    knobs["holdout_corpus_path"] = str(tiny_base["holdout"])
    runner = overrides.pop("runner", None)
    return SubprocessTrainingFn(
        run_root=tmp_path / "attempts",
        project_template=template,
        registry_path=overrides.pop("registry_path", None),
        envelope=overrides.pop("envelope", _envelope()),
        registry=overrides.pop("registry", _admitted_registry()),
        firewall=overrides.pop("firewall", ContaminationFirewall()),
        sources=overrides.pop("sources", None) or {},
        material=overrides.pop("material", None) or {},
        runner=runner,
        python=sys.executable,
        environment={"TOKENIZERS_PARALLELISM": "false"},
        timeout_seconds=overrides.pop("timeout_seconds", 900.0),
        **overrides,
    )


