    def _write_then_strand_a_sibling(cwd: Path, project: Mapping[str, Any]) -> str | None:
        artifact = original(cwd, project)
        sys.path.insert(0, str(SRC))
        from chowder.models import Experiment, ExperimentResult, Hypothesis
