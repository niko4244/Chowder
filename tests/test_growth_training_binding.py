class _RecordingRunner:
    """A runner that records commands and fakes a terminal, clean production run.

    It reads the same ``project.json`` the real CLI reads, so the registry rows,
    artifact and declared identity land where production would put them -- the
    binding's assertions are then about the binding, not about a fixture's idea
    of where things go.
    """

    def __init__(self, *, validate_returncode: int = 0, print_summary: bool = True,
                 create_registry_rows: bool = True, write_identity: bool = True,
                 artifact: bool = True, gpu_hours: float = 0.02,
                 device_gpu_hours: float | None = None) -> None:
        self.commands: list[tuple[str, ...]] = []
        self.validate_returncode = validate_returncode
        self.print_summary = print_summary
        self.create_registry_rows = create_registry_rows
        self.write_identity = write_identity
        self.artifact = artifact
        #: Wall-charged cost this fake run reports, the way the trainer does.
        self.gpu_hours = gpu_hours
        #: Device time, reported only when a run actually separates it. None
        #: models the trainer's ordinary summary, which reports wall only.
        self.device_gpu_hours = device_gpu_hours

    def __call__(self, command, cwd, environment, timeout):  # noqa: ANN001, ARG002
        self.commands.append(tuple(command))
        verb = command[-2] if len(command) >= 2 else ""
        if verb == "project-validate":
            return SubprocessOutcome(
                command=tuple(command),
                returncode=self.validate_returncode,
                stdout=json.dumps({"ok": True}) if self.validate_returncode == 0 else "",
                stderr="" if self.validate_returncode == 0 else "invalid configuration",
                seconds=0.01,
                timed_out=False,
            )
        project = json.loads((Path(cwd) / "project.json").read_text(encoding="utf-8"))
        experiment_id = project["experiment"]["experiment_id"]
        artifact_ref = self._write_run(Path(cwd), project) if self.create_registry_rows else None
        stdout = ""
        if self.print_summary:
            summary: dict[str, Any] = {
                "project": "growth-binding",
                "experiment_id": experiment_id,
                "succeeded": True,
                "promoted_experiment_id": None,
                "artifact_ref": artifact_ref,
                "metrics": {"holdout_loss": 0.5},
                "gpu_hours": self.gpu_hours,
                "error": None,
            }
            if self.device_gpu_hours is not None:
                summary["device_gpu_hours"] = self.device_gpu_hours
            stdout = "event: started\n" + json.dumps(
                summary, indent=2, sort_keys=True
            )
        return SubprocessOutcome(
            command=tuple(command), returncode=0, stdout=stdout, stderr="",
            seconds=1.0, timed_out=False,
        )

    def _write_run(self, cwd: Path, project: Mapping[str, Any]) -> str | None:
        sys.path.insert(0, str(SRC))
        from chowder.models import Experiment, ExperimentResult, Hypothesis
        from chowder.registry import RunRegistry

        experiment_id = project["experiment"]["experiment_id"]
        work_dir = Path(project["work_dir"])
        artifact = work_dir / "artifact"
        artifact.mkdir(parents=True, exist_ok=True)
        if self.artifact:
            (artifact / "payload.safetensors").write_bytes(b"payload")
            (artifact / "router_payload.json").write_text(
                json.dumps({"steps_completed": 4}), encoding="utf-8"
            )
        if self.write_identity:
            (work_dir / "chowder-identity.json").write_text(
                json.dumps(_identity_of_this_process()), encoding="utf-8"
            )
        registry = RunRegistry(Path(project["registry_path"]))
        try:
            registry.record_experiment(
                Experiment(
                    experiment_id=experiment_id,
                    parent_id=None,
                    hypothesis=Hypothesis(
                        observation="o", suspected_cause="c", intervention="i"
                    ),
                    config_patch={},
                    estimated_gpu_hours=0.1,
                )
            )
            registry.record_result(
                ExperimentResult(
                    experiment_id=experiment_id,
                    metrics={"holdout_loss": 0.5},
                    gpu_hours=self.gpu_hours,
                    artifact_ref=str(artifact),
                    evidence=(
                        {}
                        if self.device_gpu_hours is None
                        else {"device_gpu_hours": self.device_gpu_hours}
                    ),
                )
            )
            registry.update_experiment_status(experiment_id, "passed")
        finally:
            registry.close()
        return str(artifact) if self.artifact else None


def _identity_of_this_process() -> dict[str, Any]:
    sys.path.insert(0, str(SRC))
    from chowder.worker_env import chowder_source_identity

    return chowder_source_identity()


def _binding(tmp_path: Path, *, runner, registry: DataRegistry | None = None,
             firewall: ContaminationFirewall | None = None,
             material: Mapping[str, Sequence[str]] | None = None,
             template: Mapping[str, Any] | None = None, items=None,
             sources: Mapping[str, str] | None = None,
             envelope: GrowthEnvelope | None = None,
             registry_path: Path | None = None,
             attempt_files: Mapping[str, Sequence[str]] | None = None) -> SubprocessTrainingFn:
    items = items if items is not None else _items()
    item_ids = [item.item_id for item in items]
    return SubprocessTrainingFn(
        run_root=tmp_path / "attempts",
        project_template=template if template is not None else _template(tmp_path),
        registry_path=registry_path,
        envelope=envelope or _envelope(),
        registry=registry if registry is not None else _admitted_registry(),
        firewall=firewall if firewall is not None else ContaminationFirewall(),
        sources=sources or {item_id: "src-1" for item_id in item_ids},
        material=material if material is not None else _material(items),
        attempt_files=attempt_files,
        runner=runner,
        python=sys.executable,
    )


def _admitted_registry() -> DataRegistry:
    registry = DataRegistry()
    registry.register(admit(_source("src-1"), decision="included", reason="qualified"))
    return registry


